#!/usr/bin/env python3
"""Encode the six approved donut originals for the two native LVGL versions.

Deterministic build-time conversion only; no PNG decoder or image allocation
on the miner. The original PNGs and prompt/hash manifest remain unchanged.
"""
from pathlib import Path
import hashlib
import json
from collections import deque
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "branding/candidate-donuts"


def thumbnail(image, side):
    alpha = image.getchannel("A").point(lambda value: 255 if value >= 32 else 0)
    bounds = alpha.getbbox()
    if not bounds:
        raise ValueError("Candidate artwork is empty")
    art = ImageOps.contain(image.crop(bounds), (side - 4, side - 4), Image.Resampling.LANCZOS)
    canvas = Image.new("RGBA", (side, side))
    canvas.alpha_composite(art, ((side - art.width) // 2, (side - art.height) // 2))
    return canvas


def byte_array(name, data):
    rows = [", ".join(f"0x{value:02x}" for value in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"static const uint8_t {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def rgb565_alpha(image, swap):
    result = bytearray()
    pixels = image.tobytes()
    for offset in range(0, len(pixels), 4):
        r, g, b, a = pixels[offset:offset + 4]
        value = (r >> 3) << 11 | (g >> 2) << 5 | b >> 3
        lo, hi = value & 255, value >> 8
        result.extend((hi, lo, a) if swap else (lo, hi, a))
    return result


def mono_i1(image):
    # The 26px OLED version emphasizes the glaze silhouette and keeps the hole
    # and bright sprinkles. Pixels outside the artwork stay black.
    opaque = [[image.getpixel((x, y))[3] >= 128 for x in range(image.width)] for y in range(image.height)]
    outside = set()
    queue = deque((x, y) for y in range(image.height) for x in range(image.width)
                  if x in (0, image.width - 1) or y in (0, image.height - 1))
    while queue:
        x, y = queue.popleft()
        if (x, y) in outside or opaque[y][x]:
            continue
        outside.add((x, y))
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            xx, yy = x + dx, y + dy
            if 0 <= xx < image.width and 0 <= yy < image.height:
                queue.append((xx, yy))
    # At 26px the original transparent aperture can collapse to a pinhole.
    # Widen only an enclosed central alpha hole by one pixel for OLED legibility.
    aperture = set()
    for y in range(image.height // 4, image.height * 3 // 4):
        for x in range(image.width // 4, image.width * 3 // 4):
            if not opaque[y][x] and (x, y) not in outside:
                aperture.update((x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1))
    result = bytearray((0, 0, 0, 255, 255, 255, 255, 255))
    for y in range(image.height):
        row = bytearray((image.width + 7) // 8)
        for x in range(image.width):
            r, g, b, a = image.getpixel((x, y))
            luminance = (r * 299 + g * 587 + b * 114) // 1000
            if a >= 128 and luminance >= 100 and (x, y) not in aperture:
                row[x // 8] |= 1 << (7 - x % 8)
        result.extend(row)
    return result


def main(oled_root=None):
    manifest = json.loads((SOURCE / "prompts.json").read_text())
    files = manifest["files"]
    if len(files) != 6:
        raise ValueError("Expected exactly six approved originals")
    artwork = []
    for entry in files:
        source = SOURCE / Path(entry["file"]).name
        if hashlib.sha256(source.read_bytes()).hexdigest() != entry["sha256"]:
            raise ValueError(f"Original hash mismatch: {source.name}")
        with Image.open(source) as image:
            artwork.append(image.convert("RGBA"))
    comment = ("// Generated by tools/generate_candidate_assets.py from the unchanged\n"
               "// approved originals in Nerd source branding/candidate-donuts (prompts.json).\n"
               "// Only presentation assets: no block-verification or mining policy.\n")
    color = "#pragma once\n#include \"lvgl.h\"\n" + comment
    color += "// 115,200 pixel bytes in flash; the active byte order is compiled once.\nnamespace FiveTratumDisplay {\nconstexpr unsigned DonutCandidateCount = 6;\n"
    for index, image in enumerate(artwork):
        scaled = thumbnail(image, 80)
        color += "#if LV_COLOR_16_SWAP\n"
        color += byte_array(f"donutCandidatePixels{index}", rgb565_alpha(scaled, True))
        color += "#else\n" + byte_array(f"donutCandidatePixels{index}", rgb565_alpha(scaled, False)) + "#endif\n"
    color += "static const lv_img_dsc_t donutCandidateImages[6] = {\n"
    for index in range(6):
        color += f"    {{{{LV_IMG_CF_TRUE_COLOR_ALPHA, 0, 0, 80, 80}}, sizeof(donutCandidatePixels{index}), donutCandidatePixels{index}}},\n"
    color += "};\n} // namespace FiveTratumDisplay\n"
    (ROOT / "main/displays/display_candidate_assets.h").write_text(color)
    mono = "#pragma once\n#include \"lvgl.h\"\n" + comment + "// 672 palette/pixel bytes in flash; no runtime decoder.\n"
    for index, image in enumerate(artwork):
        mono += byte_array(f"oled_donut_pixels_{index}", mono_i1(thumbnail(image, 26)))
    mono += "static const lv_image_dsc_t oled_donut_variants[6] = {\n"
    for index in range(6):
        mono += ("    {.header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_I1, .w = 26, .h = 26, .stride = 4},\n"
                 f"     .data_size = sizeof(oled_donut_pixels_{index}), .data = oled_donut_pixels_{index}}},\n")
    mono += "};\n"
    if oled_root is not None:
        (Path(oled_root) / "main/oled_donut_assets.h").write_text(mono)
    print("Encoded approved donut assets; original hashes verified (115,200 colour bytes, 672 optional OLED bytes).")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--oled-root", type=Path, help="Optional full-repository Gamma root")
    args = parser.parse_args()
    if args.oled_root is not None and not (args.oled_root / "main/oled_display_layout.h").is_file():
        parser.error("--oled-root must be the Gamma source root")
    main(args.oled_root)
